const localizedJobs = { de: jobsDe, fr: jobsFr, es: jobsEs, nl: nlJobs };

jobs.forEach((job) => {
  Object.entries(localizedJobs).forEach(([locale, translations]) => {
    const translated = translations[job.slug];
    if (!translated) return;
    job.seo[locale] = translated.seo;
    job.copy[locale] = translated.copy;
  });
});

export function getJob(slug) {
  return jobs.find((job) => job.slug === slug);
}

export function jobCopy(job, locale) {
  return job.copy[locale] || job.copy.ru;
}
